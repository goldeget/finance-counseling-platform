// Generate a wrangler.production.jsonc for redeployment to a new account.
// Makes redeploy reproducible and less error-prone by templating all account-specific values.
export function generateWranglerConfig(params) {
  const {
    name = 'finance-counseling',
    accountId,
    d1DatabaseId,
    primaryHost,
    adminHost,
    backupHost,
    supabaseUrl,
    supabasePublishableKey,
    accessTeamDomain,
    accessAud,
    adminEmail,
  } = params;

  const errors = [];
  if (!accountId || !/^[0-9a-f]{32}$/.test(accountId)) errors.push('accountId must be a 32-hex Cloudflare account id');
  if (!d1DatabaseId || !/^[0-9a-f-]{36}$/.test(d1DatabaseId)) errors.push('d1DatabaseId must be a UUID');
  if (!primaryHost || !/^[\w.-]+$/.test(primaryHost)) errors.push('primaryHost is required');
  if (!adminHost || !/^[\w.-]+$/.test(adminHost)) errors.push('adminHost is required');
  if (!backupHost || !/^[\w.-]+$/.test(backupHost)) errors.push('backupHost is required');
  if (!supabaseUrl || !supabaseUrl.startsWith('https://') || !supabaseUrl.endsWith('.supabase.co')) errors.push('supabaseUrl must be an https *.supabase.co URL');
  if (!supabasePublishableKey || !supabasePublishableKey.startsWith('sb_publishable_')) errors.push('supabasePublishableKey must start with sb_publishable_');
  if (!accessTeamDomain || !/^[\w.-]+$/.test(accessTeamDomain)) errors.push('accessTeamDomain is required');
  if (!accessAud || !/^[\w-]+$/.test(accessAud)) errors.push('accessAud is required');
  if (!adminEmail || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(adminEmail)) errors.push('adminEmail must be a valid email');

  if (errors.length) throw Error('Invalid redeploy parameters: ' + errors.join('; '));

  return {
    name,
    account_id: accountId,
    compatibility_date: '2024-11-01',
    main: 'dist/worker.mjs',
    vars: {
      ADMIN_EMAIL: adminEmail,
      PRIMARY_HOST: primaryHost,
      ADMIN_HOST: adminHost,
      SUPABASE_URL: supabaseUrl,
      SUPABASE_PUBLISHABLE_KEY: supabasePublishableKey,
      ACCESS_TEAM_DOMAIN: accessTeamDomain,
      ACCESS_AUD: accessAud,
    },
    d1_databases: [
      {binding: 'DB', database_name: 'finance-counseling', database_id: d1DatabaseId},
    ],
    routes: [
      {pattern: primaryHost, custom_domain: true},
      {pattern: adminHost, custom_domain: true},
    ],
    services: [
      {binding: 'BACKUP_WORKER', service: 'finance-counseling-app-backup'},
    ],
    observability: {enabled: true},
  };
}

export function formatJsonc(config) {
  const json = JSON.stringify(config, null, 2);
  // Add a header comment for context
  return '// Generated by independent/redeploy-config.mjs — do not edit by hand.\n' + json + '\n';
}
