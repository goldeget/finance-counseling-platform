import {test} from 'node:test';
import assert from 'node:assert/strict';
import {generateWranglerConfig, formatJsonc} from '../redeploy-config.mjs';

const validParams = {
  accountId: 'a'.repeat(32),
  d1DatabaseId: '12345678-1234-1234-1234-123456789012',
  primaryHost: 'finance.example.com',
  adminHost: 'admin.finance.example.com',
  backupHost: 'finance-counseling-app-backup.example.workers.dev',
  supabaseUrl: 'https://example.supabase.co',
  supabasePublishableKey: 'sb_publishable_abcdef123456',
  accessTeamDomain: 'example.cloudflareaccess.com',
  accessAud: 'finance-admin-aud',
  adminEmail: 'admin@example.com',
};

test('generateWranglerConfig produces a valid config object', () => {
  const config = generateWranglerConfig(validParams);
  assert.equal(config.name, 'finance-counseling');
  assert.equal(config.account_id, validParams.accountId);
  assert.equal(config.compatibility_date, '2024-11-01');
  assert.equal(config.main, 'dist/worker.mjs');
  assert.equal(config.vars.PRIMARY_HOST, 'finance.example.com');
  assert.equal(config.vars.SUPABASE_URL, 'https://example.supabase.co');
  assert.equal(config.d1_databases[0].binding, 'DB');
  assert.equal(config.d1_databases[0].database_id, validParams.d1DatabaseId);
  assert.equal(config.routes.length, 2);
  assert.equal(config.observability.enabled, true);
});

test('generateWranglerConfig rejects an invalid account id', () => {
  assert.throws(() => generateWranglerConfig({...validParams, accountId: 'short'}), /accountId/);
});

test('generateWranglerConfig rejects a non-supabase URL', () => {
  assert.throws(() => generateWranglerConfig({...validParams, supabaseUrl: 'https://example.com'}), /supabaseUrl/);
  assert.throws(() => generateWranglerConfig({...validParams, supabaseUrl: 'http://example.supabase.co'}), /supabaseUrl/);
});

test('generateWranglerConfig rejects an invalid publishable key', () => {
  assert.throws(() => generateWranglerConfig({...validParams, supabasePublishableKey: 'old_key_format'}), /supabasePublishableKey/);
});

test('generateWranglerConfig rejects an invalid admin email', () => {
  assert.throws(() => generateWranglerConfig({...validParams, adminEmail: 'not-an-email'}), /adminEmail/);
});

test('generateWranglerConfig rejects an invalid D1 database id', () => {
  assert.throws(() => generateWranglerConfig({...validParams, d1DatabaseId: 'not-a-uuid'}), /d1DatabaseId/);
});

test('formatJsonc adds a header comment and trailing newline', () => {
  const config = generateWranglerConfig(validParams);
  const text = formatJsonc(config);
  assert.ok(text.startsWith('// Generated by'));
  assert.ok(text.endsWith('\n'));
  assert.ok(text.includes('"account_id"'));
});
